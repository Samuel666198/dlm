//! 「外部下载」的数据整理：不属于队列、但仍然在这台机器上下载的活儿。
//!
//! ## 为什么需要它
//!
//! 2026-11-27 用户问「插件请求的按理桌面端该有记录吧」。答案是：**只有 GUI 自己派发的任务
//! 才进 `queue.json`**。浏览器在 GUI 没开时会走宿主直连（现在会先尝试拉起 GUI，拉不起来才
//! 直连），HLS 也永远走直连 —— 这些下载在队列里没有记录，用户只能看扩展的悬浮球。
//!
//! 但它们的**断点文件是共用的**：`<落点>/<名>.dlm.json`。所以桌面端可以被动发现它们：
//! 扫落点目录就够了，不用改宿主、也不用让 CLI 学会写队列（那是 `FLAG_ADD_ONLY` 的历史欠账，
//! 两个进程写同一份队列的并发风险不值得）。
//!
//! ## 展示方式（用户裁定）
//!
//! 第一版做成列表上方一条独立的横带，用户看后说「很丑」，要求**并进队列列表**、
//! 加一个「外部」标签。所以现在：
//!
//! - 行由 [`super::list`] 画（`external_row`），与任务行同高同列，只多一枚「外部」胶囊；
//! - **不计入**左侧任何计数（它们不是队列任务）；
//! - 只读：没有勾选框、没有右键菜单 —— 外部进程的命令行不认我们的暂停信号；
//! - 只看得到**进行中/失败**的：成功收尾会删断点文件，下完就没影了。
//!
//! 本模块只保留"把队列里已有的排掉"这一条纯逻辑，渲染交给 list。

use crate::queue::External;

/// 排掉队列里已经有的同名任务 —— 那可能就是 GUI 自己在下，断点文件当然也在。
/// 不排掉的话，同一个文件会同时出现在「任务行」和「外部行」两处。
pub(crate) fn without_known(
    items: Vec<External>,
    known: &std::collections::HashSet<String>,
) -> Vec<External> {
    items
        .into_iter()
        .filter(|e| !known.contains(&e.name))
        .collect()
}
